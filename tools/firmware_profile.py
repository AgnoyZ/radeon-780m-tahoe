"""Generate immutable firmware metadata from the reviewed lock and header audit; no firmware bytes."""
import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
# The reference sequence, with PSP enum values checked against Linux 7d0a66e4.
# TOC uses LOAD_TOC, not LOAD_IP_FW type 24. MEC's jump table is not added implicitly.
RECIPE = (
    ("psp_13_0_4_toc.bin", "toc", 0),
    ("gc_11_0_1_pfp.bin", "ucode", 2),
    ("gc_11_0_1_me.bin", "ucode", 1),
    ("gc_11_0_1_mec.bin", "instruction", 4),
    ("sdma_6_0_1.bin", "context", 71),
    ("sdma_6_0_1.bin", "control", 72),
    ("gc_11_0_1_mes_2.bin", "instruction", 33),
    ("gc_11_0_1_mes_2.bin", "data", 34),
    ("gc_11_0_1_mes1.bin", "instruction", 81),
    ("gc_11_0_1_mes1.bin", "data", 82),
    ("gc_11_0_1_imu.bin", "instruction", 68),
    ("gc_11_0_1_imu.bin", "data", 69),
    ("gc_11_0_1_rlc.bin", "restore_gpm", 20),
    ("gc_11_0_1_rlc.bin", "restore_srm", 21),
    ("gc_11_0_1_rlc.bin", "iram", 26),
    ("gc_11_0_1_rlc.bin", "dram", 48),
    ("gc_11_0_1_rlc.bin", "rlcp", 25),
    ("gc_11_0_1_rlc.bin", "ucode", 8),
)


def profile(lock, audit):
    digest = hashlib.sha256(json.dumps(lock, sort_keys=True, separators=(",", ":")).encode()).hexdigest()
    manifest = audit["manifest"]
    if manifest["lock_sha256"] != digest or audit["source_commit"] != lock["upstream"]["commit"]:
        raise ValueError("Firmware audit and lock are different revisions")
    expected_names = {name for name, _, _ in RECIPE}
    entries = lock["files"]
    observed = manifest["files"]
    if (len(entries) != 9 or len(observed) != 9 or
            {e["name"] for e in entries} != expected_names or {e["name"] for e in observed} != expected_names):
        raise ValueError("Firmware profile requires the exact nine reviewed inputs")
    files, steps = [], []
    for entry in sorted(entries, key=lambda e: e["name"]):
        name = entry["name"]
        if not re.fullmatch(r"[a-z0-9_]+\.bin", name) or not re.fullmatch(r"[0-9a-f]{64}", entry["sha256"]):
            raise ValueError("Invalid firmware identity")
        actual = next(e for e in observed if e["name"] == name)
        for key in ("sha256", "size_bytes", "kind", "header_version", "ip_version"):
            if entry[key] != actual[key]: raise ValueError("Audited firmware identity differs from lock")
        if type(entry["size_bytes"]) is not int or not 0 < entry["size_bytes"] <= 16 * 1024 * 1024:
            raise ValueError("Invalid firmware size")
        header = actual["header_size_bytes"]
        if type(header) is not int or not 32 <= header <= entry["size_bytes"]:
            raise ValueError("Invalid audited firmware header size")
        files.append({"name": name, "sha256": entry["sha256"], "size_bytes": entry["size_bytes"]})
    for name, component, fw_type in RECIPE:
        actual = next(e for e in observed if e["name"] == name)
        found = [c for c in actual["components"] if c["component"] == component]
        if len(found) != 1: raise ValueError("Missing or repeated firmware component")
        region = found[0]
        offset, size = region["file_offset"], region["size_bytes"]
        if (type(offset) is not int or type(size) is not int or offset < actual["header_size_bytes"] or
                offset % 4 or size <= 0 or size % 4 or offset > actual["size_bytes"] or size > actual["size_bytes"] - offset):
            raise ValueError("Firmware component leaves its reviewed file")
        steps.append({"file_index": next(i for i, e in enumerate(files) if e["name"] == name),
                      "component": component, "file_offset": offset, "size_bytes": size, "fw_type": fw_type})
    return {"lock_sha256": digest, "files": files, "steps": steps}


def render(data):
    lines = ["/* Generated by tools/firmware_profile.py. Metadata only; target compatibility is unverified. */",
             "#ifndef PHX_780M_FIRMWARE_PROFILE_H", "#define PHX_780M_FIRMWARE_PROFILE_H", "#include <stdint.h>",
             '#define PHX_FW_LOCK_SHA256 "' + data["lock_sha256"] + '"',
             "#define PHX_FW_FILE_COUNT 9u", "#define PHX_FW_STEP_COUNT 18u",
             "struct PhxFirmwareFile { const char *name; const char *sha256; uint32_t bytes; };",
             "struct PhxFirmwareStep { uint32_t file_index, offset, bytes, fw_type; };",
             "static const struct PhxFirmwareFile phxFirmwareFiles[PHX_FW_FILE_COUNT] = {"]
    for entry in data["files"]:
        lines.append('    {"%s", "%s", %uu},' % (entry["name"], entry["sha256"], entry["size_bytes"]))
    lines += ["};", "static const struct PhxFirmwareStep phxFirmwareSteps[PHX_FW_STEP_COUNT] = {"]
    for step in data["steps"]:
        lines.append("    {%uu, %uu, %uu, %uu}," % (step["file_index"], step["file_offset"], step["size_bytes"], step["fw_type"]))
    return "\n".join(lines + ["};", "#endif", ""])


def load_profile(root=ROOT):
    lock = json.loads((root / "firmware.lock.json").read_text())
    audit = json.loads((root / "docs/validation/firmware-08624cd.json").read_text())
    return profile(lock, audit)


def checked_header(root=ROOT):
    generated = render(load_profile(root))
    output = root / "src/PhxFirmwareProfile.h"
    if not output.exists() or output.read_text(encoding="utf-8") != generated:
        raise ValueError("Firmware profile header differs from reviewed metadata")
    return generated.encode("utf-8")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = ROOT / "src/PhxFirmwareProfile.h"
    generated = render(load_profile())
    if args.check:
        if not output.exists() or output.read_text() != generated:
            parser.exit(1, "Firmware profile header differs from reviewed metadata\n")
    else:
        output.write_text(generated, encoding="utf-8", newline="\n")
